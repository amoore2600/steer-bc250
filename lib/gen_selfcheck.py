#!/usr/bin/env python3
"""gen_selfcheck.py <taskdir>... -- build the agent-visible self-check testbench of a rebuild / bugfix task.

Writes <taskdir>/selfcheck/:
  tb_selfcheck.v  + tb_selfcheck_vectors.vh    (Verilog tasks; the vectors are `include'd at compile time)
  tb_selfcheck.vhd + tb_selfcheck_vectors.vhd  (VHDL tasks; the vectors are a package analysed with the DUT)
  selfcheck.json  (files for the workspace, hdl-check arguments, seed, cycles, grader seeds)
  README.txt      (how it was made; seeds; NOT copied into the agent workspace)

The testbench instantiates only <top> (the agent's module), drives it with the same stimulus code, clocks, reset and
input timing as the hidden equivalence test (task.json "equiv", same templates as gen_vtb.py / gen_vhtb.py), from a
seed the grader does not use, and compares every output at the same sample points against values recorded by
simulating the golden module alone with that stimulus.  Golden X/Z/U bits are don't-care.  Expected values are
stored as a change list (check index, concatenated outputs) and compiled in, because hdl-check.sh runs vvp / ghdl -r
from a temporary directory where a runtime-relative vector file would not be found.

Testbench tasks are skipped (the testbench is their deliverable).
"""
import json, os, re, shutil, subprocess, sys, tempfile

LIB = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, LIB)
from gen_vhtb import to_slv  # noqa: E402

LIGHT = os.path.join(LIB, "light.sh")
GHDL_FLAGS = ["--std=08", "-fsynopsys", "-frelaxed"]
SELFCHECK_SEED = 9001           # first choice; bumped past any grader seed of the task
HDL_CHECK = "bash ~/.config/opencode/skills/hdl-check/hdl-check.sh"
VHDL_MAX_CYCLES = 60000         # hdl-check.sh runs ghdl -r with --stop-time=1ms = 100000 cycles of the 10 ns tclk
SCRATCH = os.environ.get("SELFCHECK_SCRATCH", os.path.join(tempfile.gettempdir(), "selfcheck_gen"))
# Per-task cycle counts for the self-check (default: the equivalence test's default "cycles").
CYCLES_OVERRIDE = {}


def run(cmd, timeout, cwd=None):
    p = subprocess.run([LIGHT, str(timeout)] + cmd, cwd=cwd, capture_output=True, text=True, errors="replace")
    return p.returncode, p.stdout + p.stderr


def expand(p, td):
    p = os.path.expanduser(p)
    return p if os.path.isabs(p) else os.path.join(td, p)


def grader_seeds(eq):
    out = []
    for s in eq.get("seeds", [1, 2, 3]):
        out.append(s[0] if isinstance(s, list) else s)
    return out


def pick_seed(eq):
    s = SELFCHECK_SEED
    gs = set(grader_seeds(eq))
    while s in gs:
        s += 1
    return s


def sc_cycles(cfg):
    eq = cfg["equiv"]
    n = CYCLES_OVERRIDE.get(cfg["id"], cfg.get("selfcheck_cycles") or eq.get("cycles", 4000))
    if cfg["language"] == "vhdl":
        n = min(n, VHDL_MAX_CYCLES)
    return n


# ----------------------------------------------------------------------------------------------------------- Verilog
def v_ports(td):
    return [tuple(p) for p in json.load(open(os.path.join(td, "ports.json")))["ports"]]


def v_tb(cfg, td, mode, seed, cycles, nev=0):
    """mode 'record': golden as <top>, seed from +seed (default `seed`), prints input/output change lists.
    mode 'check': the agent's <top>, fixed seed, compares against tb_selfcheck_vectors.vh."""
    eq = cfg["equiv"]
    top = cfg["top"]
    ports = v_ports(td)
    params = eq.get("params", {})
    clocks = eq["clocks"]
    cnames = {c["name"] for c in clocks}
    step = eq.get("step", 1.0)
    outs = [(n, w) for n, d, w in ports if d == "output"]
    ins = [(n, w) for n, d, w in ports if d == "input" and n not in cnames]
    wo = sum(w for _, w in outs)
    wi = sum(w for _, w in ins)
    p = ["`timescale 1ns/10ps", "`default_nettype wire"]
    if mode == "check":
        p.append("// Self-check testbench: drives your %s with a fixed random stimulus and compares every output against" % top)
        p.append("// known-correct values recorded from the reference implementation (X bits of the reference are not checked).")
        p.append("// Do not edit this file or tb_selfcheck_vectors.vh.  Prints PASS, or FAIL lines for the first mismatches.")
    p.append("module tb_selfcheck;")
    p.append("    integer seed, seed0, errs, checks, known, cyc, cycles;")
    for n, d, w in ports:
        rng = "" if w == 1 else "[%d:0] " % (w - 1)
        if d == "input":
            p.append("    reg  %s%s = 0;" % (rng, n))
        else:
            p.append("    wire %sdut_%s;" % (rng, n))
    pm = ""
    if params:
        pm = " #(" + ", ".join(".%s(%s)" % (k, v) for k, v in params.items()) + ")"
    conns = [".%s(%s)" % (n, n if d == "input" else "dut_" + n) for n, d, w in ports]
    p.append("    %s%s dut (%s);" % (top, pm, ", ".join(conns)))
    p.append("    function [31:0] r32(input integer dummy); begin r32 = $random(seed); end endfunction")
    p.append("    function [63:0] r64(input integer dummy); begin r64 = {$random(seed), $random(seed)}; end endfunction")
    p.append("    // chance(n): true with probability n/256")
    p.append("    function chance(input integer n); reg [7:0] v; begin v = $random(seed); chance = (v < n); end endfunction")
    p.append(eq.get("decls", ""))
    for c in clocks:
        p.append("    initial begin #(%s); forever #(%s) %s = ~%s; end" % (c.get("phase", 0), c["half"], c["name"], c["name"]))
    main_clk = clocks[0]["name"]
    p.append("    always @(posedge %s) cyc <= cyc + 1;" % main_clk)
    for c in clocks:
        code = eq["stim"].get(c["name"], "")
        if code:
            p.append("    always @(negedge %s) begin\n%s\n    end" % (c["name"], code))
    p.append("    reg [%d:0] sc_cur;" % (wo - 1))
    cat_o = "{" + ", ".join("dut_" + n for n, _ in outs) + "}"
    st = state_list(cfg)
    ws = sum(x["width"] for x in st)
    cat_s = "{" + ", ".join("dut.%s" % x["expr"] for x in st) + "}" if st else ""
    if mode == "record":
        p.append("    reg [%d:0] sc_prev_o; reg [%d:0] sc_cur_i, sc_prev_i;" % (wo - 1, max(wi, 1) - 1))
        if st:
            p.append("    reg [%d:0] sc_cur_s, sc_prev_s;" % (ws - 1))
        p.append("    task check; begin")
        p.append("        sc_cur = %s;" % cat_o)
        p.append("        if (checks == 0 || sc_cur !== sc_prev_o) $display(\"O %0d %b\", checks, sc_cur);")
        p.append("        sc_prev_o = sc_cur;")
        if ins:
            p.append("        sc_cur_i = {" + ", ".join(n for n, _ in ins) + "};")
            p.append("        if (checks == 0 || sc_cur_i !== sc_prev_i) $display(\"I %0d %b\", checks, sc_cur_i);")
            p.append("        sc_prev_i = sc_cur_i;")
        if st:
            p.append("        sc_cur_s = %s;" % cat_s)
            p.append("        if (checks == 0 || sc_cur_s !== sc_prev_s) $display(\"S %0d %b\", checks, sc_cur_s);")
            p.append("        sc_prev_s = sc_cur_s;")
        p.append("        checks = checks + 1;")
        p.append("    end endtask")
    else:
        # signals compared: every output, then every state entry marked compare (its name exists in the candidate)
        sigs = [("output", n, w, "dut_" + n) for n, w in outs] + [("state", x["name"], x["width"], "dut." + x["expr"])
                                                               for x in st if x.get("compare")]
        ns = len(sigs)
        p.append("    integer sc_ptr, sc_sptr, kn_t, sc_k, sc_first; reg bad_t;")
        p.append("    integer sc_nerr [0:%d]; integer sc_fcyc [0:%d];   // per signal: mismatching sample points, first cycle"
                 % (ns - 1, ns - 1))
        p.append("    reg [%d:0] sc_badv;" % (ns - 1))
        if st:
            p.append("    reg [%d:0] sc_exp_s;" % (ws - 1))
        p.append("`include \"tb_selfcheck_vectors.vh\"")
        p.append("    task automatic cmp_bits_(input [1023:0] g, input [1023:0] c, input integer w, output reg bad, output integer kn);")
        p.append("        integer i;")
        p.append("        begin bad = 0; kn = 0;")
        p.append("            if (g === c) begin if (^g[1023:0] !== 1'bx) kn = w; end")
        p.append("            else for (i = 0; i < w; i = i + 1) if (g[i] === 1'b0 || g[i] === 1'b1) begin")
        p.append("                kn = kn + 1; if (c[i] !== g[i]) bad = 1; end")
        p.append("        end")
        p.append("    endtask")
        # expected slices of each compared signal
        exp = []
        off = wo
        for n, w in outs:
            off -= w
            exp.append("sc_cur[%d:%d]" % (off + w - 1, off))
        soff = ws
        sexp = {}
        for x in st:
            soff -= x["width"]
            sexp[x["name"]] = "sc_exp_s[%d:%d]" % (soff + x["width"] - 1, soff)
        exp += [sexp[x["name"]] for x in st if x.get("compare")]
        # the block printed once, at the first sample point where anything differs
        p.append("    task show_first; integer sh; begin")
        p.append("        $display(\"FAIL: first mismatch at cycle %0d (sample point %0d); every value below is from that sample point\", cyc, checks);")
        for i in range(0, min(len(ins), 18), 6):
            grp = ins[i:i + 6]
            p.append("        $display(\"FAIL:   inputs %s\", %s);" % (" ".join("%s=%%h" % n for n, _ in grp), ", ".join(n for n, _ in grp)))
        if len(ins) > 18:
            p.append("        $display(\"FAIL:   inputs (%d more not shown)\");" % (len(ins) - 18))
        p.append("        sh = 0;")
        for i, (kind, n, w, got) in enumerate(sigs):
            p.append("        if (sc_badv[%d]) begin if (sh < 6) $display(\"FAIL:   %s %s expected %%h got %%h (wrong bits %%h)\", %s, %s, %s ^ %s); sh = sh + 1; end"
                     % (i, kind, n, exp[i], got, exp[i], got))
        p.append("        if (sh > 6) $display(\"FAIL:   (%0d more signals differ at this sample point)\", sh - 6);")
        p.append("        sh = 0; $write(\"FAIL:   outputs that match here:\");")
        for i, (n, w) in enumerate(outs):
            p.append("        if (!sc_badv[%d]) begin if (sh < 10) $write(\" %s=%%h\", dut_%s); sh = sh + 1; end" % (i, n, n))
        p.append("        if (sh > 10) $write(\" (+%0d more)\", sh - 10);")
        p.append("        $display(\"\");")
        for x in [x for x in st if not x.get("compare")][:4]:
            p.append("        $display(\"FAIL:   state %s expected %%h (reference value; print your own to compare)\", %s);" % (x["name"], sexp[x["name"]]))
        p.append("    end endtask")
        p.append("    task check; begin")
        p.append("        while (sc_ptr + 1 < SC_NEV && sc_ev_k[sc_ptr + 1] <= checks) sc_ptr = sc_ptr + 1;")
        p.append("        sc_cur = sc_ev_v[sc_ptr];")
        if st:
            p.append("        while (sc_sptr + 1 < SC_NSEV && sc_sev_k[sc_sptr + 1] <= checks) sc_sptr = sc_sptr + 1;")
            p.append("        sc_exp_s = sc_sev_v[sc_sptr];")
        p.append("        sc_badv = 0;")
        for i, (kind, n, w, got) in enumerate(sigs):
            p.append("        cmp_bits_(%s, %s, %d, bad_t, kn_t); known = known + kn_t;" % (exp[i], got, w))
            p.append("        if (bad_t) begin errs = errs + 1; sc_badv[%d] = 1'b1; if (sc_nerr[%d] == 0) sc_fcyc[%d] = cyc; sc_nerr[%d] = sc_nerr[%d] + 1; end"
                     % (i, i, i, i, i))
        p.append("        if (sc_badv != 0 && !sc_first) begin sc_first = 1; show_first; end")
        p.append("        checks = checks + 1;")
        p.append("    end endtask")
        p.append("    task summary; integer sh; begin")
        p.append("        sh = 0;")
        for i, (kind, n, w, got) in enumerate(sigs):
            p.append("        if (sc_nerr[%d] != 0) begin if (sh < 5) $display(\"FAIL: %s %s: %%0d mismatching sample points, first at cycle %%0d\", sc_nerr[%d], sc_fcyc[%d]); sh = sh + 1; end"
                     % (i, kind, n, i, i))
        p.append("        if (sh > 5) $display(\"FAIL: (%0d more signals fail)\", sh - 5);")
        p.append("        sh = 0; $write(\"  pass: outputs that match at every sample point:\");")
        for i, (n, w) in enumerate(outs):
            p.append("        if (sc_nerr[%d] == 0) begin if (sh < 12) $write(\" %s\"); sh = sh + 1; end" % (i, n))
        p.append("        if (sh == 0) $write(\" none\"); if (sh > 12) $write(\" (+%0d more)\", sh - 12);")
        p.append("        $display(\"\");")
        p.append("    end endtask")
    p.append("    initial begin")
    p.append("        errs = 0; checks = 0; known = 0; cyc = 0;")
    if mode == "record":
        p.append("        if (!$value$plusargs(\"seed=%%d\", seed)) seed = %d;" % seed)
        p.append("        if (!$value$plusargs(\"cycles=%%d\", cycles)) cycles = %d;" % cycles)
    else:
        p.append("        sc_ptr = 0; sc_sptr = 0; sc_first = 0;")
        p.append("        for (sc_k = 0; sc_k < %d; sc_k = sc_k + 1) begin sc_nerr[sc_k] = 0; sc_fcyc[sc_k] = -1; end" % ns)
        p.append("        seed = %d;" % seed)
        p.append("        cycles = %d;" % cycles)
    p.append("        seed0 = seed;")
    p.append(eq.get("init", ""))
    p.append("        #(%s);" % (step / 2.0))
    p.append("        while (cyc < cycles) begin check; #(%s); end" % step)
    if mode == "record":
        p.append("        $display(\"N %0d\", checks);")
    else:
        p.append("        if (checks != SC_NCHECKS) begin errs = errs + 1;")
        p.append("            $display(\"FAIL: testbench ran %0d checks, the vectors hold %0d\", checks, SC_NCHECKS); end")
        p.append("        if (errs == 0) begin")
        p.append("            $display(\"selfcheck: seed %d, %%0d cycles, %%0d sample points, %%0d known output bits compared\", cyc, checks, known);" % seed)
        p.append("            $display(\"PASS\");")
        p.append("        end else begin summary; $display(\"FAIL: %0d mismatches\", errs); end")
    p.append("        $finish;")
    p.append("    end")
    p.append("endmodule")
    return "\n".join(p) + "\n", outs, ins


def state_list(cfg):
    """task.json "selfcheck_state": [{"name", "expr" (path inside the module), "width", "compare"}] (Verilog only).
    compare=true when the candidate is required to have the same register (section jobs: the skeleton declares it)."""
    return [dict(x, expr=x.get("expr", x["name"])) for x in cfg.get("selfcheck_state", [])]


def v_literal(bits):
    w = len(bits)
    if re.fullmatch(r"[01]+", bits):
        return "%d'h%x" % (w, int(bits, 2))
    return "%d'b%s" % (w, bits.lower())


def v_vectors(events, nchecks, wo, sevents=None, ws=0):
    L = ["// Expected outputs recorded from the reference implementation: sc_ev_v[i] holds from sample point sc_ev_k[i] on.",
         "    localparam integer SC_NEV = %d;" % len(events),
         "    localparam integer SC_NCHECKS = %d;" % nchecks,
         "    reg [%d:0] sc_ev_v [0:%d];" % (wo - 1, len(events) - 1),
         "    integer sc_ev_k [0:%d];" % (len(events) - 1),
         "    initial begin"]
    for i, (k, b) in enumerate(events):
        L.append("        sc_ev_k[%d] = %d; sc_ev_v[%d] = %s;" % (i, k, i, v_literal(b)))
    L.append("    end")
    if sevents:
        L += ["// Reference values of the listed internal state: sc_sev_v[i] holds from sample point sc_sev_k[i] on.",
              "    localparam integer SC_NSEV = %d;" % len(sevents),
              "    reg [%d:0] sc_sev_v [0:%d];" % (ws - 1, len(sevents) - 1),
              "    integer sc_sev_k [0:%d];" % (len(sevents) - 1),
              "    initial begin"]
        for i, (k, b) in enumerate(sevents):
            L.append("        sc_sev_k[%d] = %d; sc_sev_v[%d] = %s;" % (i, k, i, v_literal(b)))
        L.append("    end")
    return "\n".join(L) + "\n"


def parse_rec(out, sv=None):
    ev, iv, n = [], [], None
    for l in out.splitlines():
        m = re.match(r"^([OIS]) (\d+) ([01xzXZUWLH\-]+)\s*$", l.strip())
        if m:
            dst = {"O": ev, "I": iv, "S": sv if sv is not None else []}[m.group(1)]
            dst.append((int(m.group(2)), m.group(3)))
            continue
        m = re.match(r"^N (\d+)\s*$", l.strip())
        if m:
            n = int(m.group(1))
    return ev, iv, n


def v_record(cfg, td, W, seed, cycles):
    eq = cfg["equiv"]
    tb, outs, ins = v_tb(cfg, td, "record", seed, cycles)
    open(os.path.join(W, "tb_record.v"), "w").write(tb)
    gold = [os.path.join(td, "golden", f) for f in cfg["golden_files"]]
    ctx = [expand(f, td) for f in cfg.get("context_files", [])]
    sim_extra = [expand(f, td) for f in eq.get("sim_extra", [])]
    rc, out = run(["iverilog", "-g2012", "-o", os.path.join(W, "rec.vvp"), os.path.join(W, "tb_record.v")] + gold + ctx + sim_extra, 300)
    if rc != 0:
        raise SystemExit("record compile failed: " + out[-600:])
    return outs, ins


def v_record_run(W, seed, cycles, sv=None):
    rc, out = run(["vvp", "-n", os.path.join(W, "rec.vvp"), "+seed=%d" % seed, "+cycles=%d" % cycles], 600, cwd=W)
    ev, iv, n = parse_rec(out, sv)
    if rc != 0 or n is None or not ev:
        raise SystemExit("record run failed rc=%d: %s" % (rc, out[-600:]))
    return ev, iv, n


# -------------------------------------------------------------------------------------------------------------- VHDL
def vh_width(t):
    tl = t.lower().replace(" ", "")
    if tl == "std_logic":
        return 1
    m = re.search(r"\((\d+)(downto|to)(\d+)\)", tl)
    if m and re.match(r"(std_logic_vector|signed|unsigned)\(", tl):
        return abs(int(m.group(1)) - int(m.group(3))) + 1
    return None


def vh_tb(cfg, mode, seed, cycles):
    eq = cfg["equiv"]
    top = cfg["top"]
    ports = eq["vports"]
    clk = eq.get("clock")
    outs = [(pt[0], pt[2], vh_width(pt[2])) for pt in ports if pt[1] == "out"]
    for n, t, w in outs:
        if w is None:
            raise SystemExit("unsupported output type %s %s" % (n, t))
    ins = [(pt[0], pt[2], vh_width(pt[2])) for pt in ports if pt[1] == "in" and pt[0] != clk and vh_width(pt[2])]
    wo = sum(w for _, _, w in outs)
    wi = sum(w for _, _, w in ins)
    p = []
    if mode == "check":
        p.append("-- Self-check testbench: drives your %s with a fixed random stimulus and compares every output against" % top)
        p.append("-- known-correct values recorded from the reference implementation ('U'/'X' bits of the reference are not checked).")
        p.append("-- Do not edit this file or tb_selfcheck_vectors.vhd.  Prints PASS, or FAIL lines for the first mismatches.")
    p.append("library ieee; use ieee.std_logic_1164.all; use ieee.numeric_std.all; use ieee.math_real.all;")
    p.append("use std.textio.all;")
    p.append(eq.get("uses", ""))
    if mode == "check":
        p.append("use work.tb_selfcheck_vectors.all;")
        p.append("entity tb_selfcheck is end entity;")
    else:
        p.append("entity tb_selfcheck is generic (SEED : integer := %d; CYCLES : integer := %d); end entity;" % (seed, cycles))
    p.append("architecture sim of tb_selfcheck is")
    if mode == "check":
        p.append("    constant SEED : integer := %d;" % seed)
        p.append("    constant CYCLES : integer := %d;" % cycles)
    p.append("    signal tclk : std_logic := '0';")
    p.append("    signal done : boolean := false;")
    p.append("    signal cyc  : integer := 0;")
    for pt in ports:
        n, d, t = pt[0], pt[1], pt[2]
        if d == "in":
            init = eq.get("init_values", {}).get(n)
            if init is None:
                init = "'0'" if t.lower() == "std_logic" else "(others => '0')"
            if n == clk:
                continue
            p.append("    signal %s : %s := %s;" % (n, t, init))
        else:
            p.append("    signal dut_%s : %s;" % (n, t))
    p.append("begin")
    p.append("    tclk <= not tclk after 5 ns when not done;")
    conc = [l for l in eq.get("conc", "").splitlines() if not re.search(r"\bg_", l)]
    if conc:
        p.append("\n".join(conc))
    conns = []
    for pt in ports:
        n, d = pt[0], pt[1]
        conns.append("%s => %s" % (n, ("tclk" if n == clk else n) if d == "in" else "dut_" + n))
    p.append("    dut : entity work.%s port map (%s);" % (top, ", ".join(conns)))
    p.append("    stim : process")
    p.append("        variable s1 : positive := SEED; variable s2 : positive := SEED * 7919 + 13; variable rr : real;")
    p.append("        impure function rb return std_logic is begin uniform(s1, s2, rr); if rr < 0.5 then return '0'; else return '1'; end if; end function;")
    p.append("        impure function rv(n : natural) return std_logic_vector is variable v : std_logic_vector(n - 1 downto 0); begin")
    p.append("            for i in v'range loop v(i) := rb; end loop; return v; end function;")
    p.append("        impure function chance(n : natural) return boolean is begin uniform(s1, s2, rr); return rr * 256.0 < real(n); end function;")
    p.append("    begin")
    p.append(eq.get("init", ""))
    p.append("        for k in 0 to CYCLES - 1 loop")
    p.append("            wait until falling_edge(tclk);")
    p.append("            cyc <= k;")
    p.append(eq["stim"])
    p.append("        end loop;")
    p.append("        wait until falling_edge(tclk);")
    p.append("        done <= true; wait;")
    p.append("    end process;")
    cat_o = " & ".join(to_slv("dut_" + n, t) for n, t, _ in outs)
    p.append("    chk : process")
    p.append("        variable sc_errs, sc_checks, sc_known, sc_r : integer := 0;")
    p.append("        variable sc_l : line;")
    p.append("        variable sc_cur : std_logic_vector(%d downto 0);" % (wo - 1))
    if mode == "record":
        p.append("        variable sc_prev_o : std_logic_vector(%d downto 0);" % (wo - 1))
        if ins:
            p.append("        variable sc_cur_i, sc_prev_i : std_logic_vector(%d downto 0);" % (wi - 1))
    else:
        p.append("        variable sc_ptr : natural := 0;")
        p.append("        variable sc_g, sc_c : std_logic_vector(%d downto 0);" % (max(w for _, _, w in outs) - 1))
        p.append("        type sc_int_arr is array (0 to %d) of integer;" % (len(outs) - 1))
        p.append("        variable sc_nerr : sc_int_arr := (others => 0);    -- per output: mismatching sample points")
        p.append("        variable sc_fcyc : sc_int_arr := (others => -1);   -- per output: first mismatching cycle")
        p.append("        variable sc_badv : std_logic_vector(0 to %d);" % (len(outs) - 1))
        p.append("        variable sc_first : boolean := false;")
        p.append("        variable sc_sh : integer;")
        p.append("        function sc_mism(g, c : std_logic_vector) return integer is")
        p.append("            variable k : integer := 0; variable cc : std_logic_vector(g'range) := c;")
        p.append("        begin")
        p.append("            for i in g'range loop")
        p.append("                if g(i) = '0' or g(i) = '1' then")
        p.append("                    if cc(i) /= g(i) then return -1; end if; k := k + 1;")
        p.append("                end if;")
        p.append("            end loop;")
        p.append("            return k;")
        p.append("        end function;")
    p.append("    begin")
    p.append("        while not done loop")
    p.append("            wait until falling_edge(tclk) or done;")
    p.append("            exit when done;")
    p.append("            wait for 4 ns;")
    p.append("            sc_cur := %s;" % cat_o)
    if mode == "record":
        p.append("            if sc_checks = 0 or sc_cur /= sc_prev_o then write(sc_l, string'(\"O \") & integer'image(sc_checks) & \" \" & to_string(sc_cur)); writeline(output, sc_l); end if;")
        p.append("            sc_prev_o := sc_cur;")
        if ins:
            p.append("            sc_cur_i := %s;" % " & ".join(to_slv(n, t) for n, t, _ in ins))
            p.append("            if sc_checks = 0 or sc_cur_i /= sc_prev_i then write(sc_l, string'(\"I \") & integer'image(sc_checks) & \" \" & to_string(sc_cur_i)); writeline(output, sc_l); end if;")
            p.append("            sc_prev_i := sc_cur_i;")
    else:
        p.append("            while sc_ptr + 1 < SC_NEV and SC_EV(sc_ptr + 1).k <= sc_checks loop sc_ptr := sc_ptr + 1; end loop;")
        off = wo
        sl = []
        for i, (n, t, w) in enumerate(outs):
            off -= w
            sl.append("(%d downto %d)" % (off + w - 1, off))
            p.append("            sc_g(%d downto 0) := SC_EV(sc_ptr).v%s; sc_c(%d downto 0) := sc_cur%s;" % (w - 1, sl[i], w - 1, sl[i]))
            p.append("            sc_r := sc_mism(sc_g(%d downto 0), sc_c(%d downto 0)); sc_badv(%d) := '0';" % (w - 1, w - 1, i))
            p.append("            if sc_r < 0 then sc_errs := sc_errs + 1; sc_badv(%d) := '1'; if sc_nerr(%d) = 0 then sc_fcyc(%d) := cyc; end if; "
                     "sc_nerr(%d) := sc_nerr(%d) + 1; else sc_known := sc_known + sc_r; end if;" % (i, i, i, i, i))
        # the block printed once, at the first sample point where anything differs
        p.append("            if not sc_first and sc_badv /= (sc_badv'range => '0') then")
        p.append("                sc_first := true;")
        p.append("                write(sc_l, string'(\"FAIL: first mismatch at cycle \") & integer'image(cyc) & \" (sample point \" & integer'image(sc_checks)"
                 " & \"); every value below is from that sample point\"); writeline(output, sc_l);")
        for k in range(0, min(len(ins), 18), 6):
            grp = ins[k:k + 6]
            p.append("                write(sc_l, string'(\"FAIL:   inputs\")%s); writeline(output, sc_l);"
                     % "".join(" & \" %s=\" & to_hstring(%s)" % (n, to_slv(n, t)) for n, t, _ in grp))
        if len(ins) > 18:
            p.append("                write(sc_l, string'(\"FAIL:   inputs (%d more not shown)\")); writeline(output, sc_l);" % (len(ins) - 18))
        p.append("                sc_sh := 0;")
        for i, (n, t, w) in enumerate(outs):
            p.append("                if sc_badv(%d) = '1' then if sc_sh < 6 then write(sc_l, string'(\"FAIL:   output %s expected \") & to_hstring(SC_EV(sc_ptr).v%s)"
                     " & \" got \" & to_hstring(sc_cur%s) & \" (wrong bits \" & to_hstring(SC_EV(sc_ptr).v%s xor sc_cur%s) & \")\"); writeline(output, sc_l); end if;"
                     " sc_sh := sc_sh + 1; end if;" % (i, n, sl[i], sl[i], sl[i], sl[i]))
        p.append("                if sc_sh > 6 then write(sc_l, string'(\"FAIL:   (\") & integer'image(sc_sh - 6) & \" more outputs differ at this sample point)\"); writeline(output, sc_l); end if;")
        p.append("                sc_sh := 0; write(sc_l, string'(\"FAIL:   outputs that match here:\"));")
        for i, (n, t, w) in enumerate(outs):
            p.append("                if sc_badv(%d) = '0' then if sc_sh < 10 then write(sc_l, string'(\" %s=\") & to_hstring(sc_cur%s)); end if; sc_sh := sc_sh + 1; end if;"
                     % (i, n, sl[i]))
        p.append("                writeline(output, sc_l);")
        p.append("            end if;")
    p.append("            sc_checks := sc_checks + 1;")
    p.append("        end loop;")
    if mode == "record":
        p.append("        write(sc_l, string'(\"N \") & integer'image(sc_checks)); writeline(output, sc_l);")
    else:
        p.append("        if sc_checks /= SC_NCHECKS then sc_errs := sc_errs + 1;")
        p.append("            write(sc_l, string'(\"FAIL: testbench ran \") & integer'image(sc_checks) & \" checks, the vectors hold \" & integer'image(SC_NCHECKS)); writeline(output, sc_l);")
        p.append("        end if;")
        p.append("        if sc_errs = 0 then")
        p.append("            write(sc_l, string'(\"selfcheck: seed \") & integer'image(SEED) & \", \" & integer'image(CYCLES) & \" cycles, \" & integer'image(sc_checks)"
                 " & \" sample points, \" & integer'image(sc_known) & \" known output bits compared\"); writeline(output, sc_l);")
        p.append("            write(sc_l, string'(\"PASS\")); writeline(output, sc_l);")
        p.append("        else")
        p.append("            sc_sh := 0;")
        for i, (n, t, w) in enumerate(outs):
            p.append("            if sc_nerr(%d) /= 0 then if sc_sh < 5 then write(sc_l, string'(\"FAIL: output %s: \") & integer'image(sc_nerr(%d)) & "
                     "\" mismatching sample points, first at cycle \" & integer'image(sc_fcyc(%d))); writeline(output, sc_l); end if; sc_sh := sc_sh + 1; end if;"
                     % (i, n, i, i))
        p.append("            if sc_sh > 5 then write(sc_l, string'(\"FAIL: (\") & integer'image(sc_sh - 5) & \" more outputs fail)\"); writeline(output, sc_l); end if;")
        p.append("            sc_sh := 0; write(sc_l, string'(\"  pass: outputs that match at every sample point:\"));")
        for i, (n, t, w) in enumerate(outs):
            p.append("            if sc_nerr(%d) = 0 then if sc_sh < 12 then write(sc_l, string'(\" %s\")); end if; sc_sh := sc_sh + 1; end if;" % (i, n))
        p.append("            if sc_sh = 0 then write(sc_l, string'(\" none\")); end if;")
        p.append("            writeline(output, sc_l);")
        p.append("            write(sc_l, string'(\"FAIL: \") & integer'image(sc_errs) & \" mismatches\"); writeline(output, sc_l);")
        p.append("        end if;")
    p.append("        std.env.finish;")
    p.append("        wait;")
    p.append("    end process;")
    p.append("end architecture;")
    return "\n".join(p) + "\n", outs, ins


def vh_vectors(events, nchecks, wo):
    L = ["-- Expected outputs recorded from the reference implementation: SC_EV(i).v holds from sample point SC_EV(i).k on.",
         "library ieee; use ieee.std_logic_1164.all;",
         "package tb_selfcheck_vectors is",
         "    type sc_ev_t is record k : natural; v : std_logic_vector(%d downto 0); end record;" % (wo - 1),
         "    type sc_ev_arr is array (natural range <>) of sc_ev_t;",
         "    constant SC_NCHECKS : natural := %d;" % nchecks,
         "    constant SC_NEV : natural := %d;" % len(events),
         "    constant SC_EV : sc_ev_arr(0 to %d) := (" % (len(events) - 1)]
    body = []
    for i, (k, b) in enumerate(events):
        body.append("        %d => (%d, \"%s\")" % (i, k, b.upper()) if len(events) == 1 else "        (%d, \"%s\")" % (k, b.upper()))
    L.append(",\n".join(body))
    L.append("    );")
    L.append("end package;")
    return "\n".join(L) + "\n"


def vh_record(cfg, td, W, seed, cycles):
    eq = cfg["equiv"]
    tb, outs, ins = vh_tb(cfg, "record", seed, cycles)
    open(os.path.join(W, "tb_record.vhd"), "w").write(tb)
    wd = "--workdir=" + W
    pre = [expand(f, td) for f in eq.get("vhdl_pre", [])]
    ctx = [expand(f, td) for f in cfg.get("context_files", [])]
    gold = [os.path.join(td, "golden", f) for f in cfg["golden_files"]]
    for f in pre + ctx + gold + [os.path.join(W, "tb_record.vhd")]:
        rc, out = run(["ghdl", "-a"] + GHDL_FLAGS + [wd, f], 300)
        if rc != 0:
            raise SystemExit("record analysis failed (%s): %s" % (f, out[-600:]))
    rc, out = run(["ghdl", "-e"] + GHDL_FLAGS + [wd, "tb_selfcheck"], 300, cwd=W)
    if rc != 0:
        raise SystemExit("record elaboration failed: " + out[-600:])
    return outs, ins


def vh_record_run(W, seed, cycles):
    rc, out = run(["ghdl", "-r"] + GHDL_FLAGS + ["--workdir=" + W, "tb_selfcheck", "-gSEED=%d" % seed, "-gCYCLES=%d" % cycles,
                   "--ieee-asserts=disable"], 600, cwd=W)
    ev, iv, n = parse_rec(out)
    if rc != 0 or n is None or not ev:
        raise SystemExit("record run failed rc=%d: %s" % (rc, out[-600:]))
    return ev, iv, n


# -------------------------------------------------------------------------------------------------------------- main
def workspace_files(cfg):
    """(files copied into the workspace, hdl-check.sh arguments after --tb) for a task."""
    gname = cfg["golden_files"][0]
    ctx = [os.path.basename(c) for c in cfg.get("context_files", [])]
    if cfg["language"] == "vhdl":
        files = ["tb_selfcheck.vhd", "tb_selfcheck_vectors.vhd"]
        args = ["--tb", "tb_selfcheck.vhd", gname] + ctx + ["tb_selfcheck_vectors.vhd"]
    else:
        files = ["tb_selfcheck.v", "tb_selfcheck_vectors.vh"]
        args = ["--tb", "tb_selfcheck.v", gname] + ctx
    return files, args


def generate(td):
    cfg = json.load(open(os.path.join(td, "task.json")))
    if cfg["type"] not in ("rebuild", "bugfix") and not (cfg["type"] == "kat" and cfg.get("equiv") and cfg.get("reference")):
        print("%-28s skipped (type %s)" % (cfg["id"], cfg["type"]))
        return None
    eq = cfg["equiv"]
    seed = pick_seed(eq)
    cycles = sc_cycles(cfg)
    os.makedirs(SCRATCH, exist_ok=True)
    W = tempfile.mkdtemp(prefix=cfg["id"] + "_rec_", dir=SCRATCH)
    vhdl = cfg["language"] == "vhdl"
    if vhdl:
        outs, ins = vh_record(cfg, td, W, seed, cycles)
        ev, iv, n = vh_record_run(W, seed, cycles)
        wo = sum(w for _, _, w in outs)
    else:
        outs, ins = v_record(cfg, td, W, seed, cycles)
        sv = []
        ev, iv, n = v_record_run(W, seed, cycles, sv)
        wo = sum(w for _, w in outs)
    if any(len(b) != wo for _, b in ev):
        raise SystemExit("recorded width mismatch")
    known = sum(1 for _, b in ev for ch in b if ch in "01")
    if known == 0:
        raise SystemExit("golden outputs are never known (all X): nothing to check")
    sd = os.path.join(td, "selfcheck")
    shutil.rmtree(sd, ignore_errors=True)
    os.makedirs(sd)
    files, args = workspace_files(cfg)
    if vhdl:
        tb, _, _ = vh_tb(cfg, "check", seed, cycles)
        open(os.path.join(sd, "tb_selfcheck.vhd"), "w").write(tb)
        open(os.path.join(sd, "tb_selfcheck_vectors.vhd"), "w").write(vh_vectors(ev, n, wo))
    else:
        tb, _, _ = v_tb(cfg, td, "check", seed, cycles)
        open(os.path.join(sd, "tb_selfcheck.v"), "w").write(tb)
        open(os.path.join(sd, "tb_selfcheck_vectors.vh"), "w").write(
            v_vectors(ev, n, wo, sv, sum(x["width"] for x in state_list(cfg))))
    meta = {"task": cfg["id"], "language": cfg["language"], "top": cfg["top"], "seed": seed, "cycles": cycles,
            "sample_points": n, "output_events": len(ev), "output_bits": wo,
            "grader_seeds": eq.get("seeds", [1, 2, 3]), "files": files, "hdl_check_args": args,
            "hdl_check_cmd": HDL_CHECK + " " + " ".join(args)}
    json.dump(meta, open(os.path.join(sd, "selfcheck.json"), "w"), indent=1)
    gs = ", ".join(str(s) if not isinstance(s, list) else "%d (%d cycles)" % (s[0], s[1]) for s in eq.get("seeds", [1, 2, 3]))
    readme = [
        "Self-check testbench for task %s (generated by lib/gen_selfcheck.py)." % cfg["id"],
        "",
        "Files copied into the agent workspace: %s." % ", ".join(files),
        "This README.txt and selfcheck.json stay here (not given to the agent).",
        "",
        "Self-check seed: %d, %d cycles of the main clock, %d sample points, %d recorded output changes (%d output bits)."
        % (seed, cycles, n, len(ev), wo),
        "Hidden grader (grade.py, task.json equiv.seeds) seeds: %s (default %d cycles)." % (gs, eq.get("cycles", 4000)),
        "The self-check seed is not one of the grader seeds, so the agent never sees the graded stimulus.",
        "",
        "Stimulus: the same task.json equiv stimulus code, clocks, reset sequence and input timing as tb_equiv.%s"
        % ("vhd" if vhdl else "v"),
        "(inputs change after the falling clock edge; outputs sampled at the same points as the grader:",
        ("4 ns after every falling edge of the 10 ns tclk)." if vhdl else
         "every %s ns, offset by half a step)." % eq.get("step", 1.0)),
        "Expected values: the golden module simulated alone with that stimulus (golden X/Z/U bits are don't-care).",
        "Parameters/generics overridden as in the grader: %s." % (json.dumps(eq.get("params", {})) if not vhdl else "none"),
        "",
        "Agent command (from the workspace directory):",
        "  " + meta["hdl_check_cmd"],
    ]
    if vhdl:
        pre = " prim_sim.vhd" if cfg.get("gowin") else ""
        readme += ["Direct: ghdl -a --std=08 -fsynopsys -frelaxed%s %s tb_selfcheck_vectors.vhd tb_selfcheck.vhd &&"
                   % (pre, " ".join([os.path.basename(c) for c in cfg.get("context_files", [])] + [cfg["golden_files"][0]])),
                   "        ghdl -e --std=08 -fsynopsys -frelaxed tb_selfcheck && ghdl -r --std=08 -fsynopsys -frelaxed tb_selfcheck"]
    else:
        pre = " prim_sim.v" if cfg.get("gowin") else ""
        readme += ["Direct: iverilog -g2012 -o sim tb_selfcheck.v %s%s && vvp -n sim"
                   % (" ".join([cfg["golden_files"][0]] + [os.path.basename(c) for c in cfg.get("context_files", [])]), pre)]
    open(os.path.join(sd, "README.txt"), "w").write("\n".join(readme) + "\n")
    shutil.rmtree(W, ignore_errors=True)
    print("%-28s seed %d cycles %d points %d events %d width %d" % (cfg["id"], seed, cycles, n, len(ev), wo))
    return meta


def main():
    for td in map(os.path.abspath, sys.argv[1:]):
        generate(td)


if __name__ == "__main__":
    main()
